import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

function resolveGitHashFromDotGit(repoRoot) {
  try {
    const gitDir = path.join(repoRoot, ".git");
    const headPath = path.join(gitDir, "HEAD");
    if (!fs.existsSync(headPath)) return null;

    const head = fs.readFileSync(headPath, "utf8").trim();
    if (/^[0-9a-f]{7,40}$/i.test(head)) {
      return head.slice(0, 7).toLowerCase();
    }

    if (head.startsWith("ref: ")) {
      const refName = head.slice(5).trim();
      const looseRefPath = path.join(gitDir, refName);
      if (fs.existsSync(looseRefPath)) {
        const hash = fs.readFileSync(looseRefPath, "utf8").trim();
        if (/^[0-9a-f]{7,40}$/i.test(hash)) {
          return hash.slice(0, 7).toLowerCase();
        }
      }

      const packedRefsPath = path.join(gitDir, "packed-refs");
      if (fs.existsSync(packedRefsPath)) {
        const lines = fs.readFileSync(packedRefsPath, "utf8").split(/\r?\n/);
        for (const line of lines) {
          if (!line || line.startsWith("#") || line.startsWith("^")) continue;
          const [hash, name] = line.split(" ");
          if (name === refName && hash && /^[0-9a-f]{7,40}$/i.test(hash)) {
            return hash.slice(0, 7).toLowerCase();
          }
        }
      }
    }
  } catch {
    // Fallback below
  }
  return null;
}

function getShortGitHash(repoRoot) {
  const fromDotGit = resolveGitHashFromDotGit(repoRoot);
  if (fromDotGit) return fromDotGit;

  try {
    const out = execFileSync("git", ["rev-parse", "--short=7", "HEAD"], {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    if (/^[0-9a-f]{7,}$/i.test(out)) {
      return out.slice(0, 7).toLowerCase();
    }
  } catch {
    // Ignore when git or commits are unavailable
  }

  return "0000000";
}

function formatUtcStamp(date) {
  const yyyy = String(date.getUTCFullYear());
  const mm = String(date.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(date.getUTCDate()).padStart(2, "0");
  const hh = String(date.getUTCHours()).padStart(2, "0");
  const min = String(date.getUTCMinutes()).padStart(2, "0");
  return `${yyyy}${mm}${dd}-${hh}${min}Z`;
}

const repoRoot = process.cwd();
const gitHash = getShortGitHash(repoRoot);
const timestampUtc = formatUtcStamp(new Date());
const buildVersion = `${gitHash}-${timestampUtc}`;

const outDir = path.join(repoRoot, "src", "generated");
const outFile = path.join(outDir, "build-info.ts");
fs.mkdirSync(outDir, { recursive: true });

const content = `// Auto-generated by scripts/write-build-info.mjs — do not edit manually.
export const BUILD_GIT_HASH = ${JSON.stringify(gitHash)};
export const BUILD_TIMESTAMP_UTC = ${JSON.stringify(timestampUtc)};
export const BUILD_VERSION = ${JSON.stringify(buildVersion)};
`;

fs.writeFileSync(outFile, content, "utf8");
console.log(`[build-info] ${buildVersion}`);
